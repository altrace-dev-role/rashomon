// TestSEED1b_TheCardCarriesOnlyOurWords is PF-AU2: a canary in every field a
// transcript has (paths, a command with a token-shaped secret, the person's
// words, an MCP tool's name, a hook's message, the cwd, the session id) never
// reaches the card, and every word the card prints is in Vocabulary().
func TestSEED1b_TheCardCarriesOnlyOurWords(t *testing.T) {
	const canary = "SEEDCANARY7f3e"
	tl := New()
	for i, session := range []string{"sess-" + canary + "-1", "sess-" + canary + "-2"} {
		x := &tx{t: t, session: session}
		x.add(map[string]any{"type": "user", "cwd": "/home/" + canary, "message": map[string]any{"role": "user", "content": "do it " + canary}})
		x.call("c1", "Bash", map[string]any{"command": "curl -H 'Authorization: Bearer sk-" + canary + "' https://" + canary + ".example"})
		x.result("c1", true, rejectedText+" "+canary, "user-rejected")
		x.say("do it again " + canary)
		x.call("c2", "mcp__"+canary+"__deploy", map[string]any{"target": canary})
		x.result("c2", true, "BLOCKED: "+canary+" is protected", "permission-rule")
		x.call("c3", "Edit", map[string]any{"file_path": "/src/" + canary + "_test.go", "old_string": canary, "new_string": canary})
		x.result("c3", true, "<tool_use_error>String to replace not found in file.\nString: "+canary+"</tool_use_error>", "")
		x.call("c4", "Edit", map[string]any{"file_path": "/src/" + canary + "_test.go", "old_string": "a", "new_string": canary})
		x.reply("Done " + canary)
		x.say("no, " + canary + " is wrong")
		if err := tl.Read(strings.NewReader(x.text()), "proj-"+canary+string(rune('a'+i)), false); err != nil {
			t.Fatal(err)
		}
	}
	card := Card(tl.Summary(), 14)
	if card == "" {
		t.Fatal("no card")
	}
	if strings.Contains(strings.ToUpper(card), strings.ToUpper(canary)) {
		t.Errorf("the card carries the canary:\n%s", card)
	}
	vocab := map[string]bool{}
	for _, w := range Vocabulary() {
		vocab[w] = true
	}
	for _, w := range cardWords(card) {
		if !vocab[w] {
			t.Errorf("the card prints %q, which is not in Vocabulary()", w)
		}
	}
	for _, l := range strings.Split(card, "\n") {
		if n := len([]rune(l)); n > 80 {
			t.Errorf("a card line is %d columns, over 80: %q", n, l)
		}
	}
	for _, want := range []string{"you said no to a network command", "your rules blocked an MCP tool call",
		"an edit whose text was not in the file, then tried again", "you pushed back after an edit to a test file"} {
		if !strings.Contains(card, want) {
			t.Errorf("the card does not name %q:\n%s", want, card)
		}
	}
}

// cardWords is every word the card prints that is not a number: split on
// space, with the punctuation the card's own lines use trimmed.
func cardWords(card string) []string {
	var out []string
	for _, f := range strings.Fields(card) {
		w := strings.Trim(f, ",.:;()")
		if w == "" || strings.Trim(w, "0123456789") == "" {
			continue
		}
		out = append(out, w)
	}
	return out
}

