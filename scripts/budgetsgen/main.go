// Command budgetsgen writes internal/budget/budgets_gen.go from
// test/perf/budgets.json, so that the binary's copy of the budgets and the
// perf gates' copy cannot disagree (tech spec 8.2.6). Run from the module
// root: go generate ./internal/budget
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
)

func main() {
	root, err := moduleRoot()
	if err != nil {
		fmt.Fprintln(os.Stderr, "budgetsgen:", err)
		os.Exit(1)
	}
	src := filepath.Join(root, "test", "perf", "budgets.json")
	dst := filepath.Join(root, "internal", "budget", "budgets_gen.go")
	out, err := Generate(src)
	if err != nil {
		fmt.Fprintln(os.Stderr, "budgetsgen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(dst, out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "budgetsgen:", err)
		os.Exit(1)
	}
	fmt.Printf("budgetsgen: wrote %s (%d bytes)\n", dst, len(out))
}

// moduleRoot is the directory holding go.mod, found upward from the working
// directory, so the tool runs the same from `go generate` and from a shell.
func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.mod above %s", dir)
		}
		dir = parent
	}
}

// Generate renders the Go source of budgets_gen.go from the JSON file. The
// table is embedded as the JSON text itself and decoded once at first use:
// a Go literal of the struct would be a second encoding of the same data
// with its own ways to drift, and decoding 2 KiB on first use costs nothing
// at process init (RES-2). The generator does not import internal/budget,
// which cannot compile before its generated file exists; the struct-level
// check is TestRES36_GeneratedBudgetsMatch, which decodes both copies.
func Generate(src string) ([]byte, error) {
	raw, err := os.ReadFile(src)
	if err != nil {
		return nil, err
	}
	var head struct {
		Version int `json:"budgets_version"`
	}
	if err := json.Unmarshal(raw, &head); err != nil {
		return nil, fmt.Errorf("%s: %w", src, err)
	}
	if head.Version < 1 {
		return nil, fmt.Errorf("%s: budgets_version %d", src, head.Version)
	}
	var compact bytes.Buffer
	if err := json.Compact(&compact, raw); err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by scripts/budgetsgen from test/perf/budgets.json; DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package budget\n\n")
	fmt.Fprintf(&buf, "// tableJSON is test/perf/budgets.json, compacted; Table decodes it on first use.\n")
	fmt.Fprintf(&buf, "const tableJSON = %q\n", compact.String())
	return format.Source(buf.Bytes())
}
